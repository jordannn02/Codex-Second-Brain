#!/usr/bin/env python3
"""Verify that index.md contains the current deterministic generated stats block."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import date
from pathlib import Path

from vault_stats import DEFAULT_POLICY, STATS_BEGIN, STATS_END, compute, render_block, walk_vault


SCHEMA = "index-freshness/v1"
GENERATION_LINE = re.compile(
    r"^_Generated by `scripts/vault_stats\.py` on (\d{4}-\d{2}-\d{2})\._$",
    re.MULTILINE,
)


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def stats_content(block: str, computed_on: str) -> tuple[str | None, str | None]:
    """Separate the saved rendering date from freshly recomputed statistics.

    All other bytes, including counts and activity dates, must still match.
    Invalid, duplicate or future rendering dates remain validation failures.
    """
    matches = list(GENERATION_LINE.finditer(block))
    if len(matches) != 1:
        return None, None
    rendered_on = matches[0].group(1)
    try:
        if date.fromisoformat(rendered_on) > date.fromisoformat(computed_on):
            return None, rendered_on
    except ValueError:
        return None, rendered_on
    return GENERATION_LINE.sub("<generation-date>", block, count=1), rendered_on


def inspect_index(vault: Path, policy_path: Path) -> dict[str, object]:
    index = vault / "index.md"
    policy = json.loads(policy_path.read_text(encoding="utf-8"))
    aliases = {str(key): str(value) for key, value in policy.get("type_aliases", {}).items()}
    stats = compute(walk_vault(vault), aliases, str(policy.get("schema") or "unknown"))
    expected = render_block(stats)
    current = ""
    if index.is_file():
        text = index.read_text(encoding="utf-8")
        match = re.search(re.escape(STATS_BEGIN) + r".*?" + re.escape(STATS_END), text, re.DOTALL)
        current = match.group(0) if match else ""
    expected_content, _ = stats_content(expected, stats["generated_at"])
    current_content, rendered_on = stats_content(current, stats["generated_at"])
    stale = current_content is None or current_content != expected_content
    blockers = ["index_generated_stats_stale"] if stale else []
    return {
        "schema": SCHEMA,
        "vault": str(vault),
        "index": str(index),
        "level": "degraded" if stale else "verified-working",
        "stale": stale,
        "blockers": blockers,
        "expected_block_sha256": sha256_text(expected),
        "current_block_sha256": sha256_text(current) if current else None,
        "comparison": "All freshly computed statistics and activity dates; saved rendering date reported separately.",
        "rendered_on": rendered_on,
        "generation_date_differs": rendered_on != stats["generated_at"],
        "expected_content_sha256": sha256_text(expected_content) if expected_content else None,
        "current_content_sha256": sha256_text(current_content) if current_content else None,
        "stats": {
            "generated_at": stats["generated_at"],
            "total_notes": stats["total_notes"],
            "dev_logs": stats["dev_logs"]["total"],
            "operation_logs": stats["logs"]["total"],
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vault", default=".")
    parser.add_argument("--policy", default=str(DEFAULT_POLICY))
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    try:
        vault = Path(args.vault).expanduser().resolve()
        policy = Path(args.policy).expanduser().resolve()
        if not vault.is_dir():
            raise ValueError(f"vault_not_found:{vault}")
        if not policy.is_file():
            raise ValueError(f"policy_not_found:{policy}")
        payload = inspect_index(vault, policy)
        print(json.dumps(payload, ensure_ascii=False, indent=2) if args.json else payload["level"])
        return 1 if payload["stale"] else 0
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(json.dumps({"schema": SCHEMA, "error": str(error)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
